// Type 3. - No Param/Arg but Return Type

function sayHello(){

    console.log("Hi");
    return "helllo";

}

let call = sayHello();
console.log(call);

// Explaination
// 1. We defined a function called sayHello which does not take any parameters.
// 2. Inside the function, we log "Hi" to the console and return the string "helllo".
// 3. We call the function and store its return value in the variable call.
// 4. Finally, we log the value of call to the console, which will output "helllo".

